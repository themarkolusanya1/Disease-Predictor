import streamlit as st
import pandas as pd

st.set_page_config(page_title="Prediction Result")
st.markdown("""
<style>
[data-testid="stSidebar"] {
    display: none;
}
</style>
""", unsafe_allow_html=True)

if "prediction" not in st.session_state:
    st.warning("No prediction found.")
    if st.button("⬅ Back"):
        st.switch_page("app.py")
    st.stop()

result = st.session_state.prediction

st.title("🩺 Disease Prediction Result")

st.markdown("## PREDICTION CONDITIONS:")
st.success(result["disease"])
st.balloons()

st.subheader("Prediction Confidence")

st.progress(result["confidence"] / 100)

st.metric(
    label="Model Confidence",
    value=f"{result['confidence']:.2f}%"
)

st.caption(
    "This confidence score indicates how certain the machine learning model is about its prediction. A higher percentage means the model is more confident, but it does not guarantee a correct medical diagnosis."
)

st.divider()

st.subheader("📖 Disease Description")

if not result["desc"].empty:
    st.info(result["desc"].iloc[0]["Description"])
else:
    st.info("No description available.")

st.divider()

st.subheader("💊 WHAT YOU SHOULD DO NEXT")

if not result["prec"].empty:

    for i in range(1,5):

        precaution = result["prec"].iloc[0][f"Precaution_{i}"]

        if pd.notna(precaution):
            st.success(precaution)

st.divider()

st.warning(
    "⚠ This prediction is generated by a Machine Learning model for educational purposes only. It is NOT a medical diagnosis. Please consult a qualified healthcare professional."
)

#st.success(" ✅  prediction compeleted successfully!")
st.info(
    "If symptoms persist, please consult a doctor for further evaluation and treatment."
)
st.divider()
st.subheader("💬 Feedback")

with st.form("feedback_form"):
    rating = st.slider(
        "How would you rate this prediction?",
        1, 5, 5
    )

    feedback = st.text_area(
        "Tell us how we can improve:"
    )

    submitted = st.form_submit_button("Submit Feedback")

if submitted:
    st.success("✅ Thank you! Your feedback has been received.")
    st.balloons()
if st.button("⬅️ Back"):
    st.session_state.show_results = False
    st.switch_page("app.py")

st.markdown("""
<center>

## Disease Predictor

Developed by **CAPSTONE Group 1**

Department of Healthcare Intelligence

Machine Learning Project • 2026

</center>
""", unsafe_allow_html=True)